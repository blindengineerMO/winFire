// Build documentation from registered routes in an isolated, disposable database.
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..')
process.chdir(root)
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'winfire-route-docs-'))
process.env.DATA_DIR=dir
process.env.NODE_ENV='test'
// Never read deployment secrets or contact management targets for documentation.
delete process.env.JWT_SECRET
delete process.env.VAULT_MASTER_KEY
const {app}=await import('../api/src/app.js')
const {db}=await import('../api/src/db.js')
const server=app.listen(0,'127.0.0.1')
await new Promise(resolve=>server.once('listening',resolve))
try {
  const spec=await (await fetch(`http://127.0.0.1:${server.address().port}/api/v1/openapi.json`)).json()
  const locations=new Map()
  for(const [file,router,prefix] of [['api/src/app.js','api',''],['api/src/routes/agents.js','agentRoutes','/agents'],['api/src/routes/internet.js','internetRoutes','/internet'],['api/src/routes/mapping.js','mappingRoutes','/mapping'],['api/src/routes/ai.js','aiRoutes','/ai'],['api/src/routes/protection.js','r',''],['api/src/routes/policySafety.js','r',''],['api/src/telemetry/routes.js','r',''],['api/src/cloud/routes.js','r',''],['api/src/routes/apiKeys.js','apiKeyRoutes','/api-keys']]){
    fs.readFileSync(file,'utf8').split('\n').forEach((line,index)=>{
      const match=line.match(new RegExp(`${router}\\.(get|post|patch|put|delete)\\('([^']+)'`))
      if(match)locations.set(`${match[1]} ${(prefix+match[2]).replace(/(^|\/)\:([A-Za-z]\w*)(?=\/|$)/g,'$1{$2}')}`,`../${file}#L${index+1}`)
    })
  }
  const groups=new Map()
  for(const [route,methods] of Object.entries(spec.paths))for(const [method,operation] of Object.entries(methods)){
    const group=operation.tags[0]
    if(!groups.has(group))groups.set(group,[])
    groups.get(group).push({route,method,operation})
  }
  const lines=['# API route reference','','Generated by `npm run docs:api` from the registered Express routes and OpenAPI schemas. Do not edit this file by hand. Regeneration uses a temporary SQLite database; it does not start schedulers or connect to inventory hosts.','','All paths below are relative to `/api/v1`. See [API usage and curl examples](API.md) for authentication, query conventions, workflows, and errors. Source links point to the handler with its complete validation and resource authorization checks.','','`bearerAuth` = operator access token; `mutualTLS` = enrolled agent certificate; `internetDeviceBearer` = browser device token; `wefHmac` = node-scoped WEF token; `aiReporterBearer` = bound AI reporter enrollment credential. Remote `/mcp/ai-usage` uses OAuth and is documented in [AI usage](AI_USAGE.md). “No bearer” routes can still require credentials, an enrollment token, HTTPS, or prompt-specific authorization. Permission gates are additive to per-resource grants and ownership checks.','','Some older operations publish a generic JSON body. For those, follow the linked handler; an unspecified schema does not mean that arbitrary input is accepted. Response codes in the live OpenAPI spec remain generic for some older endpoints.','']
  let count=0
  for(const [group,entries] of [...groups].sort(([a],[b])=>a.localeCompare(b))){
    lines.push(`## ${group}`,'','| Method | Route / handler | Authentication; permission | JSON body schema |','|---|---|---|---|')
    for(const {route,method,operation} of entries.sort((a,b)=>a.route.localeCompare(b.route)||a.method.localeCompare(b.method))){
      count++
      const schema=operation.requestBody?.content?.['application/json']?.schema?.$ref?.split('/').pop()
      const auth=(operation.security||[]).flatMap(value=>Object.keys(value)).join(' or ')||'No bearer'
      const permissions=(operation['x-required-permissions']||[]).join(', ')
      const link=locations.get(`${method} ${route}`)
      lines.push(`| ${method.toUpperCase()} | ${link?`[\`${route}\`](${link})`:`\`${route}\``} | ${auth}${permissions?`; ${permissions}`:''} | ${schema?`[${schema}](#${schema.toLowerCase()})`:operation.requestBody?'See handler':'—'} |`)
    }
    lines.push('')
    for(const {route,method,operation} of entries){
      const query=operation.parameters?.filter(item=>item.in==='query')||[]
      if(operation.description||query.length){
        lines.push(`**${method.toUpperCase()} ${route}**`, '')
        if(operation.description)lines.push(operation.description,'')
        if(query.length)lines.push(`Query parameters: ${query.map(item=>`\`${item.name}\` (${item.schema.type}${item.schema.default!==undefined?`; default ${item.schema.default}`:''}${item.schema.minimum!==undefined?`; min ${item.schema.minimum}`:''}${item.schema.maximum!==undefined?`; max ${item.schema.maximum}`:''})`).join(', ')}.`,'')
      }
    }
  }
  lines.push('## Schemas','','Schemas include types, required fields, allowed values, bounds, and descriptions. `$ref` names refer to other schemas in this section.','')
  for(const [name,schema] of Object.entries(spec.components.schemas).sort(([a],[b])=>a.localeCompare(b)))lines.push(`### ${name}`,'','```json',JSON.stringify(schema,null,2),'```','')
  fs.writeFileSync(path.join(root,'docs/API_ROUTES.md'),lines.join('\n'))
  console.log(`Documented ${count} API operations and ${Object.keys(spec.components.schemas).length} schemas.`)
} finally {
  await new Promise(resolve=>server.close(resolve))
  db.close()
  fs.rmSync(dir,{recursive:true,force:true})
}
